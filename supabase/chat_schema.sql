create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  conversation_id text not null,
  sender_id text not null,
  message_type text not null check (message_type in ('text', 'audio', 'video', 'image')),
  content text not null,
  file_name text,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_conversation_created_idx
  on public.chat_messages (conversation_id, created_at);

alter table public.chat_messages enable row level security;

create policy "chat messages can be read by authenticated users"
  on public.chat_messages for select to authenticated using (true);

create policy "chat messages can be created by authenticated users"
  on public.chat_messages for insert to authenticated with check (true);

alter publication supabase_realtime add table public.chat_messages;

